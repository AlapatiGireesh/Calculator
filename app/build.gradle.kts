fun getSecret(key: String, defaultValue: String): String {
    val envVal = System.getenv(key)
    if (envVal != null && envVal != "") return envVal
    val envFile = project.rootProject.file(".env")
    if (envFile.exists()) {
        try {
            val props = Properties()
            val stream = envFile.inputStream()
            props.load(stream)
            stream.close()
            val propVal = props.getProperty(key)
            if (propVal != null && propVal != "") {
                return propVal
            }
        } catch (e: Exception) {
            // Ignore properties loading errors and use fallback
        }
    }
    return defaultValue
}

